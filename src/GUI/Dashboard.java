    private void loadRoleBasedWindow(String role) {
        // Role-based tab access

        jLabel2.setText("Welcome " + name);

        switch (role) {
            case "Doctor":
                jButton4.setVisible(false); //staff
                jButton6.setVisible(false); //billing
                break;
            case "Nurse":
                jButton4.setVisible(false); //staff

                break;
            case "Pharmacist":
                jButton3.setVisible(false); //apponment
                jButton4.setVisible(false); //staff

                break;
            case "Admin":
                // Admin sees all tabs
                break;
            default:
                JOptionPane.showMessageDialog(this, "Invalid role: " + role);
                this.dispose();
                new Login().setVisible(true);
                break;
        }
    }

